#pragma once
// hwid.h — сбор аппаратных идентификаторов на Windows и хеширование в HWID.
#include <string>
#include <vector>

namespace lic {

// Собирает "сырой" набор компонентов машины и SHA-256-хеширует их
// в 32-символьную hex-строку HWID. Повторные запуски на одной машине дают
// одинаковый результат; на другой — почти наверняка другой.
std::string computeHwid();

// Возвращает дебаг-представление (компоненты по отдельности, не хеш).
// Нужно только для отладки/поддержки, не для проверки лицензии.
std::vector<std::string> rawComponents();

} // namespace lic